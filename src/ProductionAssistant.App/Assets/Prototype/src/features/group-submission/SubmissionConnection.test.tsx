import { act } from 'react'
import { createRoot, type Root } from 'react-dom/client'
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import { SubmissionConnection } from './SubmissionConnection'
import { createSubmissionSettingsMock } from './submission-settings.mock'
import { DocumentConnectionAlert, documentLink, type DocumentConnectionState } from './DocumentConnectionAlert'
import type { SubmissionSettingsAdapter } from './business-configuration.types'

const { invoke } = vi.hoisted(() => ({ invoke: vi.fn() }))
vi.mock('../../bridge/index', () => ({ invoke }))
const firstUrl = 'https://docs.qq.com/sheet/one', secondUrl = 'https://docs.qq.com/sheet/two'
// Explicit fixture evidence, never generated by the page or default adapter.
const connected: DocumentConnectionState = { state: 'connected', documentName: '设备运行时长', checkedAt: '2026-11-13T09:30:00+08:00' }
let root: Root, container: HTMLDivElement, adapter: SubmissionSettingsAdapter
const ready = vi.fn(), active = vi.fn(), dirty = vi.fn()
const button = (name: string) => [...container.querySelectorAll<HTMLButtonElement>('button')].find(element => element.textContent?.trim() === name)!
const click = async (element: HTMLElement) => act(async () => { element.click() })
const change = async (value: string) => act(async () => {
  const input = container.querySelector<HTMLInputElement>('#submission-document-url')!
  Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value')!.set!.call(input, value)
  input.dispatchEvent(new Event('input', { bubbles: true }))
})
const mount = async () => act(async () => root.render(<SubmissionConnection job={{ id: 'one', config: { documentUrl: firstUrl } }} adapter={adapter} onSaved={vi.fn()} onCreated={vi.fn()} onActive={active} onDirty={dirty} onReady={ready} />))
beforeEach(() => {
  vi.stubGlobal('IS_REACT_ACT_ENVIRONMENT', true)
  invoke.mockReset().mockResolvedValue({})
  ready.mockClear(); active.mockClear(); dirty.mockClear()
  adapter = createSubmissionSettingsMock()
  container = document.createElement('div'); document.body.append(container); root = createRoot(container)
})
afterEach(async () => { await act(async () => root.unmount()); container.remove(); vi.unstubAllGlobals() })

it.each([
  [{ state: 'idle' }, '尚未检测文档连接', false],
  [{ state: 'checking' }, '正在检测文档连接...', false],
  [connected, '已连接 · 设备运行时长 · 可编辑 · 最近检测：', false],
  [{ state: 'notLoggedIn' }, '尚未登录共享文档账号', true],
  [{ state: 'readOnly' }, '当前账号只有查看权限，无法进行数据填报', true],
  [{ state: 'invalidLink' }, '文档链接无效，请检查链接', true],
  [{ state: 'unavailable' }, '无法打开文档，请检查网络或文档访问权限', true],
] as [DocumentConnectionState, string, boolean][])('renders one Alert for %j', async (connection, text, destructive) => {
  const login = vi.fn()
  await act(async () => root.render(<DocumentConnectionAlert connection={connection} onLogin={login} />))
  const alert = container.querySelector('[data-slot=alert]')!
  expect(container.querySelectorAll('[data-slot=alert]')).toHaveLength(1)
  expect(alert.textContent).toContain(text)
  expect(alert.className.includes('text-destructive')).toBe(destructive)
  expect(alert.querySelector('.animate-spin') !== null).toBe(connection.state === 'checking')
  expect(!!container.querySelector('time')).toBe(connection.state === 'connected')
  if (connection.state === 'connected') {
    expect(alert.className).toContain('text-emerald-700')
    expect(container.querySelector('time')?.getAttribute('datetime')).toBe(connected.state === 'connected' ? connected.checkedAt : '')
  }
  expect(!!button('扫码登录')).toBe(connection.state === 'notLoggedIn')
  if (connection.state === 'notLoggedIn') { await click(button('扫码登录')); expect(login).toHaveBeenCalledOnce() }
})

it('uses a single three-part input group with a read-only supplied name and the existing opener', async () => {
  adapter.readDocumentName = url => url === firstUrl ? '设备运行时长' : url === secondUrl ? '成品入库量' : undefined
  await mount()
  const group = container.querySelector('[data-slot=input-group]')!
  expect([...group.children].map(element => element.getAttribute('data-slot'))).toEqual(['input-group-control', 'input-group-addon', 'input-group-addon'])
  expect(group.querySelectorAll('input')).toHaveLength(1)
  expect(group.querySelector('.lucide-file-text')).not.toBeNull()
  expect(group.querySelectorAll('[data-slot=button-group-separator][data-orientation=vertical]')).toHaveLength(2)
  expect(group.querySelector('[aria-label="文档名称"]')?.textContent).toBe('设备运行时长')
  expect(container.querySelector('#submission-document-note')).toBeNull()
  await change(secondUrl)
  expect(group.querySelector('[aria-label="文档名称"]')?.textContent).toBe('成品入库量')
  await click(button('打开文档'))
  expect(invoke).toHaveBeenCalledOnce()
  expect(invoke).toHaveBeenLastCalledWith('tencentSheet.sessionOpen', { documentUrl: secondUrl }, 60000)
  expect(container.querySelector('[data-connection-state]')?.getAttribute('data-connection-state')).toBe('idle')
  await change('javascript:alert(1)')
  expect(group.querySelector('[aria-label="文档名称"]')?.textContent).toBe('共享文档')
  expect(button('打开文档').disabled).toBe(true)
  expect(button('保存').disabled).toBe(true)
  await click(button('检测连接'))
  expect(container.textContent).toContain('文档链接无效，请检查链接')
})

it.each([undefined, '', '   '])('uses the shared-document fallback without inferring a name from the URL: %j', async name => {
  adapter.readDocumentName = () => name
  await mount()
  await change('https://docs.qq.com/sheet/设备运行时长?title=设备运行时长&link=' + 'long-url-'.repeat(80))
  const label = container.querySelector<HTMLElement>('[aria-label="文档名称"]')!
  expect(label.textContent).toBe('共享文档')
  expect(label.title).toBe('共享文档')
  expect(container.querySelector('[contenteditable]')).toBeNull()
  await click(label)
  expect(document.activeElement).toBe(container.querySelector('#submission-document-url'))
  expect(button('打开文档').disabled).toBe(false)
})

it('shows checking, uses only supplied evidence and resets success immediately when URL changes', async () => {
  let resolve!: (value: DocumentConnectionState) => void
  adapter.checkDocumentConnection = vi.fn(() => new Promise<DocumentConnectionState>(done => { resolve = done }))
  await mount(); await click(button('检测连接'))
  expect(container.querySelector('[data-connection-state=checking] .animate-spin')).not.toBeNull()
  expect(active).toHaveBeenLastCalledWith(true)
  expect(ready).toHaveBeenLastCalledWith(false)
  await act(async () => resolve(connected))
  expect(container.querySelector('[aria-label="文档名称"]')?.textContent).toBe('设备运行时长')
  expect(ready).toHaveBeenLastCalledWith(true)
  await change(secondUrl)
  expect(container.querySelector('[data-connection-state=idle]')).not.toBeNull()
  expect(container.querySelector('time')).toBeNull()
  expect(container.querySelector('[aria-label="文档名称"]')?.textContent).toBe('共享文档')
  expect(ready).toHaveBeenLastCalledWith(false)
})

it('ignores a late result for an edited URL and never checks on mount or window focus', async () => {
  let resolve!: (value: DocumentConnectionState) => void
  adapter.checkDocumentConnection = vi.fn(() => new Promise<DocumentConnectionState>(done => { resolve = done }))
  await mount(); await act(async () => window.dispatchEvent(new Event('focus')))
  expect(adapter.checkDocumentConnection).not.toHaveBeenCalled()
  expect(invoke).not.toHaveBeenCalled()
  await click(button('检测连接')); await change(secondUrl)
  await act(async () => resolve(connected))
  expect(container.querySelector('[data-connection-state=idle]')).not.toBeNull()
  expect(container.querySelector('time')).toBeNull()
  expect(ready).toHaveBeenLastCalledWith(false)
})

it.each([
  { state: 'connected', documentName: '', checkedAt: '2026-11-13T09:30:00+08:00' },
  { state: 'connected', documentName: '文档', checkedAt: '' },
] as DocumentConnectionState[])('does not complete a success with missing evidence: %j', async result => {
  adapter.checkDocumentConnection = vi.fn().mockResolvedValue(result)
  await mount(); await click(button('检测连接'))
  expect(container.querySelector('[data-connection-state=unavailable]')).not.toBeNull()
  expect(container.querySelector('time')).toBeNull()
  expect(ready).toHaveBeenLastCalledWith(false)
})

it('keeps QR login local and reports detector or opener failures without claiming a connection', async () => {
  adapter.checkDocumentConnection = vi.fn().mockResolvedValue({ state: 'notLoggedIn' })
  await mount(); await click(button('检测连接')); await click(button('扫码登录'))
  expect(container.textContent).toContain('扫码登录尚未接入')
  expect(invoke).not.toHaveBeenCalled()
  adapter.checkDocumentConnection = vi.fn().mockRejectedValue(new Error('fixture failure'))
  await click(button('检测连接'))
  expect(container.querySelector('[data-connection-state=unavailable]')).not.toBeNull()
  invoke.mockRejectedValueOnce(new Error('浏览器被占用'))
  await click(button('打开文档'))
  expect(container.textContent).toContain('浏览器被占用')
  expect(ready).toHaveBeenLastCalledWith(false)
})

it.each(['', 'https://docs.qq.com/', 'http://docs.qq.com/sheet/one', 'https://docs.qq.com.evil.invalid/sheet/one', 'https://user:secret@docs.qq.com/sheet/one', 'https://docs.qq.com:8080/sheet/one'])('rejects unusable or unsafe links: %s', value => {
  expect(documentLink(value)).toBeUndefined()
})
