'use strict';
const assert=require('node:assert/strict');
const {EventEmitter}=require('node:events');
const {TencentAuthentication,classify,endpoint,evidenceLifetimeMs}=require('../../src/ProductionAssistant.App/Assets/TencentSheet/authentication.cjs');
async function authenticationChecks() {
  assert.equal(classify(200,{login:true,ret:0}).authentication,'authenticated');
  assert.equal(classify(200,{ret:12100,retcode:12100}).authentication,'required');
  for(const [http,body] of [[500,{login:true,ret:0}],[200,{login:true,ret:12100}],[200,{ret:12100,cgicode:0}],[200,{login:'true',ret:0}],[200,{ret:999}],[200,null]])assert.equal(classify(http,body).authentication,'unknown');
  let clock=100000,posts=0,disposals=0,body={login:true,ret:0},failure=null,finish;
  const context=new EventEmitter();
  context.cookies=async()=>[{value:'synthetic-xsrf'}];
  context.request={post:async(url,options)=>{
    posts++;assert.equal(url,endpoint);assert.deepEqual(options.data,{xsrf:'synthetic-xsrf'});
    assert.deepEqual(options.headers,{'Content-Type':'application/json'});assert.equal(options.maxRetries,0);assert.equal(options.maxRedirects,0);
    if(finish)await new Promise(resolve=>{finish=resolve;});
    if(failure)throw failure;
    return {status:()=>200,json:async()=>body,dispose:async()=>{disposals++;}};
  }};
  const auth=new TencentAuthentication(context,{now:()=>clock});
  const request=()=>({url:()=>endpoint,method:()=> 'POST',postDataJSON:()=>({xsrf:'synthetic-xsrf'})});
  const observe=async value=>{const req=request();context.emit('request',req);context.emit('response',{request:()=>req,status:()=>200,json:async()=>value});await auth.settle();};
  assert.equal((await auth.verify()).authenticationReason,'token-not-observed');assert.equal(posts,0);
  assert.equal(auth.snapshot().authenticationDiagnostics.cookieEvidence,'present-unclassified','anonymous cookies must not be treated as login credentials');
  const emptyContext=new EventEmitter();emptyContext.cookies=async()=>[];
  const empty=new TencentAuthentication(emptyContext);
  assert.equal((await empty.verify()).authentication,'unknown','an empty cookie jar alone does not prove the server login classification');
  assert.equal(empty.snapshot().authenticationDiagnostics.cookieEvidence,'empty');empty.dispose();
  await observe({login:true,ret:0});
  const inProgress=request();context.emit('request',inProgress);
  assert.equal(auth.snapshot().authentication,'unknown','a newer in-flight observation invalidates the previous conclusion');
  context.emit('response',{request:()=>inProgress,status:()=>200,json:async()=>({login:true,ret:0})});await auth.settle();
  for(let n=0;n<20;n++)auth.snapshot();
  assert.equal(posts,0,'Status/snapshots must never POST');
  assert.equal((await auth.verify()).authentication,'authenticated');assert.equal(posts,0,'fresh passive evidence is reused');
  clock+=evidenceLifetimeMs+1;assert.equal(auth.snapshot().authentication,'unknown');
  const results=await Promise.all([auth.verify(),auth.verify(),auth.verify()]);
  assert.ok(results.every(value=>value.authentication==='authenticated'));assert.equal(posts,1);assert.equal(disposals,1);
  assert.ok(!JSON.stringify(results).includes('synthetic-xsrf'));
  assert.equal(results[0].authenticationDiagnostics.tokenMatchesCookie,true);
  assert.equal(results[0].authenticationDiagnostics.tokenReadSource,'request-body');
  const alternate={url:()=>endpoint.replace('get_vip_info=1','get_vip_info=0')+'&secret=synthetic-url-value',method:()=> 'POST',postDataJSON:()=>({xsrf:'do-not-adopt'})};
  context.emit('request',alternate);context.emit('response',{request:()=>alternate,status:()=>200});
  const diagnostic=auth.snapshot().authenticationDiagnostics;
  assert.ok(diagnostic.userInfoRequestsSeen>diagnostic.userInfoRequestsAccepted,'diagnostics reveal a filter mismatch without guessing a token');
  assert.ok(!JSON.stringify(diagnostic).includes('synthetic-url-value'));assert.ok(!JSON.stringify(diagnostic).includes('do-not-adopt'));
  context.emit('request',{url:()=> 'https://open.weixin.qq.com/connect/qrcode/short-private',method:()=> 'GET'});
  assert.ok(!JSON.stringify(auth.snapshot()).includes('short-private'),'short QR resource credentials are also redacted');
  assert.ok(JSON.stringify(auth.snapshot()).includes('/connect/qrcode/[redacted]'));
  clock+=evidenceLifetimeMs+1;failure=Error('private-cookie-value network error');
  assert.equal((await auth.verify()).authentication,'unknown');assert.equal(posts,2);
  assert.equal(auth.snapshot().authenticationSource,null,'a failed request is not a server observation');
  assert.equal(auth.snapshot().authenticationObservedAt,null);
  assert.equal((await auth.verify()).authenticationReason,'rate-limited');assert.equal(posts,2);
  assert.ok(!JSON.stringify(auth.snapshot()).includes('private-cookie'));
  await observe({ret:12100});assert.equal(auth.snapshot().authentication,'required');assert.equal(auth.snapshot().authenticationPreviouslyConfirmed,true);
  failure=null;clock+=evidenceLifetimeMs+1;finish=true;
  const pending=auth.verify();await Promise.resolve();await Promise.resolve();
  auth.dispose();if(typeof finish==='function')finish();
  assert.equal((await pending).authenticationReason,'session-closed');
  assert.equal(context.listenerCount('request'),0);assert.equal(context.listenerCount('response'),0);
  assert.equal(disposals,2);auth.dispose();
  const principalContext=new EventEmitter(),principalAuth=new TencentAuthentication(principalContext);
  const principalBody=uid=>({login:true,ret:0,uid,domain_id:'synthetic-domain',uid_source:1});
  const principalResponse=uid=>({status:()=>200,json:async()=>principalBody(uid)});
  principalAuth.publish(await principalAuth.read(principalResponse('private-user-one')));
  const firstPrincipal=principalAuth.scopeVersion;
  principalAuth.publish(await principalAuth.read(principalResponse('private-user-one')));
  assert.equal(principalAuth.scopeVersion,firstPrincipal,'same server identity does not impersonate an account switch');
  principalAuth.publish(await principalAuth.read(principalResponse('private-user-two')));
  assert.ok(principalAuth.scopeVersion>firstPrincipal,'different confirmed user invalidates scoped permission evidence');
  assert.ok(!JSON.stringify(principalAuth.snapshot()).includes('private-user'),'private identity cannot cross the snapshot allowlist');
  principalAuth.dispose();
  console.log('PASS authentication: strict server classification, passive cache, bounded probe, merged calls, freshness, redaction, close and listener cleanup');
}
if(require.main===module)authenticationChecks().catch(error=>{console.error(error);process.exitCode=1;});
module.exports={authenticationChecks};
