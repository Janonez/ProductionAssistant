const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const api = require('./core.js');
const values = {cutting: '0', welding: '28.6', section: '12.8', plate: '19.2'};
const plan = api.plan(api.defaults, '2026-09-05', values);
assert.deepEqual(plan.rows.map(r => r.address), ['J9','J19','N35','O35']);
assert.equal(plan.sheet, '下料、装焊（26年9月）');
assert.equal(api.plan(api.defaults,'2026-10-01',values).rows[0].address,'F9');
assert.equal(api.plan(api.defaults,'2026-09-30',values).rows[3].address,'BM35');
assert.equal(api.plan(api.defaults,'2028-02-29',values).date,'2028-02-29');
assert.throws(() => api.plan(api.defaults,'2026-02-29',values));
assert.throws(() => api.plan(api.defaults,'2026-09-05',{...values,cutting:''}));
assert.throws(() => api.plan({...api.defaults,weldingRow:9},'2026-09-05',values));
assert.throws(() => api.validate({...api.defaults,documentUrl:'javascript:alert(1)'}));
assert.throws(() => api.plan({...api.defaults,startColumn:'XFD'},'2026-09-05',values));
const original = {J19:'999'};
assert.throws(() => api.simulate(plan,original,'ready'), /整批停止/);
assert.deepEqual(original,{J19:'999'});
for (const scenario of ['login','permission','anchor','sheet']) assert.throws(() => api.simulate(plan,{},scenario));
const result = api.simulate(plan,{},'ready');
assert.equal(result.cells.J9,'0');
assert.throws(() => api.simulate(plan,result.cells,'ready'), /整批停止/);
for(const blank of [' ', '\n', '\r\n', '\u00a0', '\u200b', '\ufeff'])assert.equal(api.preflight(plan,{J9:blank},'ready')[0].action,'write');
for(const value of ['0','42.35','=""','文字',' \n0'])assert.equal(api.preflight(plan,{J9:value},'ready')[0].action,'conflict');
const html = fs.readFileSync(path.join(__dirname,'index.html'),'utf8');
const inline = fs.readFileSync(path.join(__dirname,'app.js'),'utf8');
new vm.Script(inline);
console.log('PASS: date/address, validation, conflicts, blocked scenarios, zero, occupied-cell rejection, script syntax');

// Reuse the project's installed DOM test dependency; no additional install.
const {JSDOM} = require('../../../src/ProductionAssistant.App/Assets/Prototype/node_modules/jsdom');
async function main() {
const dom = new JSDOM(html,{url:'http://localhost/',runScripts:'outside-only'});
const w = dom.window;
w.eval(fs.readFileSync(path.join(__dirname,'core.js'),'utf8'));
w.eval(inline);
await w.demoInitialized;
const settled = () => new Promise(resolve=>setImmediate(resolve));
const $ = id => w.document.getElementById(id);
$('sample').click();
$('date').value = '2026-09-05';
$('dataForm').dispatchEvent(new w.Event('submit',{cancelable:true}));
assert.equal($('preview').hidden,false);
assert.match($('preview').textContent,/J9/);
$('check').click();
await settled();
assert.equal($('execute').disabled,false);
$('execute').click();
await settled();
assert.match($('status').textContent,/填报 4 格/);
$('check').click(); await settled(); $('execute').click(); await settled();
assert.match($('status').textContent,/冲突/);
assert.equal($('execute').disabled,true);
const cell = $('preview').querySelector('input'); cell.value='999'; cell.dispatchEvent(new w.Event('input'));
assert.equal($('execute').disabled,true);
$('check').click(); await settled(); assert.equal($('execute').disabled,true);
assert.match($('status').textContent,/冲突/);
$('settingsTab').click(); assert.equal($('settings').hidden,false);
$('configForm').elements.company.value = '测试公司';
$('configForm').dispatchEvent(new w.Event('submit',{cancelable:true}));
await settled();
assert.equal(JSON.parse(w.localStorage.getItem('pa.tencent-docs-demo.v1')).company,'测试公司');
assert.equal($('preview').hidden,true);
dom.window.close();
console.log('PASS: UI preview, write/readback, repeat, conflict, config persistence and stale-plan invalidation');
}
main().catch(e=>{console.error(e);process.exitCode=1;});
